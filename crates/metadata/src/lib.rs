/// Node id in the metadata group.
pub type NodeId = u64;

openraft::declare_raft_types!(
    /// Raft types for the metadata group.
    pub TypeConfig:
        D = Command,
        R = Response,
);

/// A command committed through the metadata group.
#[derive(Serialize, Deserialize, Debug, Clone, PartialEq, Eq)]
pub enum Command {
    /// Insert or replace one key.
    Put { key: String, value: String },
    /// Create a topic and its partitions at offset 0.
    CreateTopic {
        /// Topic name.
        name: String,
        /// Topic id, generated by the proposer. Generating it at apply time
        /// would give each replica a different id.
        #[serde(default)]
        id: String,
        /// Partition count, at least 1.
        partitions: i32,
        /// `r2` or `wal`.
        durability: String,
    },
    /// Delete a topic by name.
    DeleteTopic {
        /// Topic name.
        name: String,
    },
    /// Publish sealed extents. Each part must start at the partition's next offset.
    Publish {
        /// Slices in commit order.
        parts: Vec<PublishPart>,
    },
    /// Publish extents and the producer sequences those batches established.
    /// Same offset rule as [`Command::Publish`]. A note that is not a fresh
    /// sequence rejects the whole command.
    PublishWithProducers {
        /// Slices in commit order.
        parts: Vec<PublishPart>,
        /// Producer batches inside those slices.
        producers: Vec<ProducerNote>,
    },
    /// Allocate a producer id, or bump its epoch. A transactional id is rejected.
    InitProducer {
        /// True when the client sent a transactional id. Phase 5.
        transactional: bool,
        /// `-1` allocates. Otherwise the id whose epoch to bump.
        producer_id: i64,
        /// Current epoch. Must match the stored epoch when `producer_id` is set.
        producer_epoch: i16,
    },
    /// Store a consumer group's record. Rejected with ILLEGAL_GENERATION when
    /// the stored generation is newer.
    SaveGroup {
        /// Group id.
        group: String,
        /// The record to store.
        record: groups::GroupRecord,
    },
    /// Commit offsets for a group, all or none. A member's commit must match
    /// the stored generation and membership (see [`groups::check_commit`]).
    CommitOffsets {
        /// Group id.
        group: String,
        /// Generation, or -1 for a commit outside group membership.
        generation: i32,
        /// Member id, empty with generation -1.
        member_id: String,
        /// Offsets to store.
        offsets: Vec<groups::OffsetCommit>,
    },
    /// Delete an empty group's record and offsets.
    DeleteGroup {
        /// Group id.
        group: String,
    },
    /// Raise a topic's partition count. Assignments are rejected.
    CreatePartitions {
        /// One entry per topic in the request.
        topics: Vec<admin::PartitionIncrease>,
    },
    /// Set or check topic configs.
    AlterConfigs {
        /// One entry per resource.
        changes: Vec<admin::ConfigChange>,
    },
    /// Move partition log starts to an object boundary.
    DeleteRecords {
        /// One entry per partition.
        cuts: Vec<admin::RecordCut>,
    },
    /// Remove committed offsets for a group.
    OffsetDelete {
        /// Group and the partitions to forget.
        forget: admin::OffsetDrop,
    },
}

/// State-machine response for [`Command`].
#[derive(Serialize, Deserialize, Debug, Clone, PartialEq, Eq)]
pub struct Response {
    /// Previous value, when the command replaced one.
    #[serde(default)]
    pub value: Option<String>,
    /// Kafka error code. `0` means the command was applied.
    #[serde(default)]
    pub error_code: i16,
}

impl Response {
    /// A command that was applied.
    pub fn ok(value: Option<String>) -> Self {
        Self {
            value,
            error_code: 0,
        }
    }

    /// A command that was rejected. The map is unchanged.
    pub fn reject(error_code: i16) -> Self {
        Self {
            value: None,
            error_code,
        }
    }
}

/// One broker's metadata Raft node.
pub struct MetadataNode {
    /// The openraft handle. Routes and tests call this directly.
    pub raft: Raft<TypeConfig>,
    machine: Arc<RedbMachine>,
}

impl MetadataNode {
    /// Open the on-disk log and state machine and start Raft.
    ///
    /// `http_addr` is the address other brokers use for Raft RPC. The HTTP
    /// server itself is started by `camus-broker`.
    pub async fn open(node_id: NodeId, dir: &Path, http_addr: &str) -> anyhow::Result<Self> {
        let _ = http_addr;
        Self::start(node_id, dir, network::HttpFactory).await
    }

    /// Open a node whose Raft RPC stays in-process, routed by `group`.
    pub async fn open_in_process(
        node_id: NodeId,
        dir: &Path,
        group: &str,
        router: Arc<SharedRouter>,
    ) -> anyhow::Result<Self> {
        let factory = network::InProcFactory {
            group: group.to_string(),
            router,
        };
        Self::start(node_id, dir, factory).await
    }

    async fn start<N>(node_id: NodeId, dir: &Path, network: N) -> anyhow::Result<Self>
    where
        N: openraft::RaftNetworkFactory<TypeConfig>,
    {
        let config = Config {
            heartbeat_interval: 50,
            election_timeout_min: 150,
            election_timeout_max: 300,
            ..Default::default()
        };
        let config = Arc::new(config.validate()?);
        let log = camus_raft::SegmentLogStore::open(dir.join("log"))?;
        let machine = Arc::new(RedbMachine::open(&dir.join("state.redb"))?);
        let raft = Raft::new(node_id, config, network, log, machine.clone()).await?;
        Ok(Self { raft, machine })
    }

    /// Register this in-process node so peers can reach it.
    pub fn register_in_process(&self, group: &str, node_id: NodeId, router: &SharedRouter) {
        router.insert(group, node_id, self.raft.clone());
    }

    /// Create the cluster. Call this once, on one voter, listing every voter.
    pub async fn initialize(&self, nodes: BTreeMap<NodeId, BasicNode>) -> anyhow::Result<()> {
        self.raft.initialize(nodes).await?;
        Ok(())
    }

    /// Commit a put. Fails when this node is not the leader.
    pub async fn write(
        &self,
        key: impl Into<String>,
        value: impl Into<String>,
    ) -> anyhow::Result<Response> {
        let response = self
            .raft
            .client_write(Command::Put {
                key: key.into(),
                value: value.into(),
            })
            .await?;
        Ok(response.data)
    }

    /// Commit a topic create. `error_code` is a Kafka code when the name is taken or the config is invalid.
    pub async fn create_topic(
        &self,
        name: impl Into<String>,
        partitions: i32,
        durability: impl Into<String>,
    ) -> anyhow::Result<Response> {
        let response = self
            .raft
            .client_write(Command::CreateTopic {
                name: name.into(),
                id: uuid::Uuid::new_v4().to_string(),
                partitions,
                durability: durability.into(),
            })
            .await?;
        Ok(response.data)
    }

    /// Commit a topic delete.
    pub async fn delete_topic(&self, name: impl Into<String>) -> anyhow::Result<Response> {
        let response = self
            .raft
            .client_write(Command::DeleteTopic { name: name.into() })
            .await?;
        Ok(response.data)
    }

    /// Commit extent metadata. The object itself is already in the bucket.
    pub async fn publish(
        &self,
        parts: Vec<PublishPart>,
        producers: Vec<ProducerNote>,
    ) -> anyhow::Result<Response> {
        let response = self
            .raft
            .client_write(Command::PublishWithProducers { parts, producers })
            .await?;
        Ok(response.data)
    }

    /// Commit an admin or group command. `value` is command-specific.
    pub async fn apply(&self, command: Command) -> anyhow::Result<Response> {
        let response = self.raft.client_write(command).await?;
        Ok(response.data)
    }

    /// Allocate or bump a producer id. `value` is `"{producer_id},{epoch}"` on success.
    pub async fn init_producer(
        &self,
        transactional: bool,
        producer_id: i64,
        producer_epoch: i16,
    ) -> anyhow::Result<Response> {
        let response = self
            .raft
            .client_write(Command::InitProducer {
                transactional,
                producer_id,
                producer_epoch,
            })
            .await?;
        Ok(response.data)
    }

    /// Commit a group command and return its Kafka error code (0 = applied).
    pub async fn group_write(&self, command: Command) -> anyhow::Result<i16> {
        let response = self.raft.client_write(command).await?;
        Ok(response.data.error_code)
    }

    /// Wait until this node, as leader, has applied everything committed
    /// before the call, so a following [`MetadataNode::read_local`] is
    /// linearizable. Fails when this node is not the leader.
    pub async fn linearizable(&self) -> anyhow::Result<()> {
        self.raft.ensure_linearizable().await?;
        Ok(())
    }

    /// Applied keys starting with `prefix`, in key order. Not linearizable on
    /// its own; call [`MetadataNode::linearizable`] first when it must be.
    pub fn scan_local(&self, prefix: &str) -> anyhow::Result<Vec<(String, String)>> {
        Ok(self.machine.scan(prefix)?)
    }

    /// Read the latest applied value on this node. This is not a linearizable read.
    pub fn read_local(&self, key: &str) -> anyhow::Result<Option<String>> {
        Ok(self.machine.get(key)?)
    }

    /// Stop Raft tasks. The files stay on disk.
    pub async fn shutdown(&self) -> anyhow::Result<()> {
        self.raft.shutdown().await?;
        Ok(())
    }
}
