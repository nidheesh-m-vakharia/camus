/// A command committed through the metadata group.
#[derive(Serialize, Deserialize, Debug, Clone, PartialEq, Eq)]
pub enum Command {
    /// Insert or replace one key.
    Put { key: String, value: String },
    /// Remove one key. Missing keys are not an error.
    Delete { key: String },
    /// Create a topic and its partitions at offset 0.
    CreateTopic {
        /// Topic name.
        name: String,
        /// Topic id, generated by the proposer. Generating it at apply time
        /// would give each replica a different id.
        #[serde(default)]
        id: String,
        /// Partition count, at least 1.
        partitions: i32,
        /// `r2` or `wal`.
        durability: String,
        /// Topic configs from the request, checked again at apply time.
        #[serde(default)]
        configs: Vec<(String, Option<String>)>,
    },
    /// Delete a topic by name.
    DeleteTopic {
        /// Topic name.
        name: String,
    },
    /// Publish sealed extents. Each part must start at the partition's next offset.
    Publish {
        /// Slices in commit order.
        parts: Vec<PublishPart>,
    },
    /// Publish extents and the producer sequences those batches established.
    /// Same offset rule as [`Command::Publish`]. A note that is not a fresh
    /// sequence rejects the whole command.
    PublishWithProducers {
        /// Slices in commit order.
        parts: Vec<PublishPart>,
        /// Producer batches inside those slices.
        producers: Vec<ProducerNote>,
    },
    /// Allocate a producer id, or bump its epoch. A transactional id is rejected.
    InitProducer {
        /// True when the client sent a transactional id. Phase 5.
        transactional: bool,
        /// `-1` allocates. Otherwise the id whose epoch to bump.
        producer_id: i64,
        /// Current epoch. Must match the stored epoch when `producer_id` is set.
        producer_epoch: i16,
    },
    /// Remove a group's committed offsets that `offsets.retention.minutes`
    /// has expired. Only an empty group loses offsets. Its retention counts
    /// from when it became empty, or from each commit for a group that only
    /// has offsets. The group itself goes once no offsets are left.
    ExpireOffsets {
        /// Group id.
        group: String,
        /// Proposer's clock.
        now_ms: i64,
        /// Kafka's `offsets.retention.minutes`, in milliseconds.
        retention_ms: i64,
    },
    /// Store a consumer group's record. Rejected with ILLEGAL_GENERATION when
    /// the stored generation is newer.
    SaveGroup {
        /// Group id.
        group: String,
        /// The record to store.
        record: groups::GroupRecord,
    },
    /// Commit offsets for a group, all or none. A member's commit must match
    /// the stored generation and membership (see [`groups::check_commit`]).
    CommitOffsets {
        /// Group id.
        group: String,
        /// Generation, or -1 for a commit outside group membership.
        generation: i32,
        /// Member id, empty with generation -1.
        member_id: String,
        /// Offsets to store.
        offsets: Vec<groups::OffsetCommit>,
    },
    /// Delete an empty group's record and offsets.
    DeleteGroup {
        /// Group id.
        group: String,
    },
    /// Raise a topic's partition count. Assignments are rejected.
    CreatePartitions {
        /// One entry per topic in the request.
        topics: Vec<admin::PartitionIncrease>,
    },
    /// Set or check topic configs.
    AlterConfigs {
        /// One entry per resource.
        changes: Vec<admin::ConfigChange>,
    },
    /// Move partition log starts to an object boundary.
    DeleteRecords {
        /// One entry per partition.
        cuts: Vec<admin::RecordCut>,
    },
    /// Remove committed offsets for a group.
    OffsetDelete {
        /// Group and the partitions to forget.
        forget: admin::OffsetDrop,
    },
    /// Allocate or bump a transactional id. An ongoing transaction is aborted.
    InitTransaction {
        /// Transactional id.
        transactional_id: String,
        /// `-1` allocates. A known id must match the stored epoch.
        producer_id: i64,
        /// Current epoch, ignored when `producer_id` is `-1`.
        producer_epoch: i16,
    },
    /// Start or continue a transaction on these partitions.
    AddTxnPartitions {
        /// Transactional id.
        transactional_id: String,
        /// Producer id.
        producer_id: i64,
        /// Producer epoch.
        producer_epoch: i16,
        /// Topic name and partition.
        partitions: Vec<(String, i32)>,
    },
    /// Record a produced range before the produce is acknowledged.
    NoteTxn {
        /// Transactional id.
        transactional_id: String,
        /// Producer id.
        producer_id: i64,
        /// Producer epoch.
        producer_epoch: i16,
        /// The range just appended.
        span: txn::TxnSpan,
    },
    /// Stage offsets that commit only with the transaction.
    StageTxnOffsets {
        /// Transactional id.
        transactional_id: String,
        /// Producer id.
        producer_id: i64,
        /// Producer epoch.
        producer_epoch: i16,
        /// Group id.
        group: String,
        /// Offsets to write on commit.
        offsets: Vec<groups::OffsetCommit>,
    },
    /// Commit or abort the ongoing transaction.
    EndTransaction {
        /// Transactional id.
        transactional_id: String,
        /// Producer id.
        producer_id: i64,
        /// Producer epoch.
        producer_epoch: i16,
        /// `true` commits.
        committed: bool,
        /// Proposer's clock. `0` in commands written before it was carried.
        #[serde(default)]
        now_ms: i64,
        /// Partition ends from the shard leaders. Empty on commands written
        /// before ADR 0015, which keep the spans `NoteTxn` stored.
        #[serde(default)]
        ends: Vec<txn::TxnSpan>,
    },
    /// Replace a sealed offset range with one object. The high watermark stays.
    /// Commands written before windows omit `covered_start` and replace the
    /// whole prefix ending at `covered_end`.
    Compact {
        /// Topic name.
        topic: String,
        /// Partition.
        partition: i32,
        /// First offset of the range. `None` replaces the prefix.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        covered_start: Option<i64>,
        /// Exclusive end of the range being replaced.
        covered_end: i64,
        /// New object key.
        object_key: String,
        /// Byte offset of the slice in the object.
        file_offset: u64,
        /// Byte length.
        length: u32,
        /// First timestamp in the rewritten slice.
        base_timestamp: i64,
        /// Last timestamp in the rewritten slice.
        max_timestamp: i64,
    },
    /// Add ACL bindings. Each binding is accepted or rejected on its own.
    CreateAcls {
        /// Bindings from the request.
        bindings: Vec<acl::Binding>,
    },
    /// Delete ACL bindings selected by each filter.
    DeleteAcls {
        /// One filter per request entry.
        filters: Vec<acl::Filter>,
    },
    /// Allocate a transactional id and store the timeout from `InitProducerId`.
    InitTransactionTimed {
        /// Transactional id.
        transactional_id: String,
        /// `-1` allocates. A known id must match the stored epoch.
        producer_id: i64,
        /// Current epoch, ignored when `producer_id` is `-1`.
        producer_epoch: i16,
        /// Client timeout in milliseconds. `0` means 60 seconds.
        timeout_ms: i32,
        /// Proposer's clock. `0` in commands written before it was carried.
        #[serde(default)]
        now_ms: i64,
    },
    /// Start or continue a transaction and record when it became ongoing.
    AddTxnPartitionsAt {
        /// Transactional id.
        transactional_id: String,
        /// Producer id.
        producer_id: i64,
        /// Producer epoch.
        producer_epoch: i16,
        /// Topic name and partition.
        partitions: Vec<(String, i32)>,
        /// Milliseconds since the epoch. Replicas share this value.
        started_ms: i64,
    },
    /// Abort a transaction that outlived its timeout and fence its producer.
    /// Applied only if the id is still at this producer and epoch.
    AbortTimedOutTxn {
        /// Transactional id.
        transactional_id: String,
        /// Producer id the proposer saw.
        producer_id: i64,
        /// Producer epoch the proposer saw.
        producer_epoch: i16,
        /// Proposer's clock.
        now_ms: i64,
    },
    /// Remove a transactional id idle for `expiration_ms`.
    ExpireTransactionalId {
        /// Transactional id.
        transactional_id: String,
        /// Producer id the proposer saw.
        producer_id: i64,
        /// Producer epoch the proposer saw.
        producer_epoch: i16,
        /// Proposer's clock.
        now_ms: i64,
        /// Kafka's `transactional.id.expiration.ms`.
        expiration_ms: i64,
    },
    /// Remove producer sequence state that Kafka would expire.
    ExpireProducers {
        /// `(topic, partition, producer_id)` of each candidate.
        keys: Vec<(String, i32, i64)>,
        /// Proposer's clock.
        now_ms: i64,
        /// Kafka's `producer.id.expiration.ms`.
        expiration_ms: i64,
    },
    /// Several commands written as one log entry, applied in order as if each
    /// were its own entry. The response holds one per command in `each`.
    /// The metadata group commit writes these; a broker that predates them
    /// cannot read one.
    Batch(Vec<Command>),
}

/// State-machine response for [`Command`].
#[derive(Serialize, Deserialize, Debug, Clone, PartialEq, Eq)]
pub struct Response {
    /// Previous value, when the command replaced one.
    #[serde(default)]
    pub value: Option<String>,
    /// Kafka error code. `0` means the command was applied.
    #[serde(default)]
    pub error_code: i16,
    /// For [`Command::Batch`]: one response per command, in order.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub each: Vec<Response>,
}

impl Response {
    /// A command that was applied.
    pub fn ok(value: Option<String>) -> Self {
        Self {
            value,
            error_code: 0,
            each: Vec::new(),
        }
    }

    /// A command that was rejected. The map is unchanged.
    pub fn reject(error_code: i16) -> Self {
        Self {
            value: None,
            error_code,
            each: Vec::new(),
        }
    }
}

/// One broker's metadata Raft node.
pub struct MetadataNode {
    /// The openraft handle. Routes and tests call this directly.
    pub raft: Raft<TypeConfig>,
    machine: Arc<RedbMachine>,
    /// Writes waiting for the group commit.
    writes: tokio::sync::mpsc::Sender<Queued>,
    /// Reads waiting for a linearizable round.
    reads: tokio::sync::mpsc::Sender<tokio::sync::oneshot::Sender<Result<(), String>>>,
}

/// A command waiting for the group commit, and where its result goes.
type Queued = (
    Command,
    tokio::sync::oneshot::Sender<Result<Response, String>>,
);

/// Most commands one metadata log entry carries.
const GROUP_COMMANDS: usize = 256;

/// Writes allowed to wait for the committer before callers wait to queue.
const QUEUED_WRITES: usize = 4096;

/// Group commit for the metadata log. Commands that arrive while entries are
/// committing go into the next entry together, so concurrent writers share
/// one log append and one quorum fsync instead of one each. Entries are
/// submitted in arrival order; two may be committing at once.
async fn write_loop(raft: Raft<TypeConfig>, mut queue: tokio::sync::mpsc::Receiver<Queued>) {
    let slots = Arc::new(tokio::sync::Semaphore::new(2));
    while let Some(first) = queue.recv().await {
        let mut group = vec![first];
        while group.len() < GROUP_COMMANDS {
            let Ok(next) = queue.try_recv() else { break };
            group.push(next);
        }
        let Ok(slot) = slots.clone().acquire_owned().await else {
            return;
        };
        // More arrived while both entries were committing; take them too.
        while group.len() < GROUP_COMMANDS {
            let Ok(next) = queue.try_recv() else { break };
            group.push(next);
        }
        let (mut commands, waiters): (Vec<_>, Vec<_>) = group.into_iter().unzip();
        let command = match commands.len() {
            1 => commands.remove(0),
            _ => Command::Batch(commands),
        };
        let submitted = raft.client_write_ff(command).await;
        tokio::spawn(async move {
            let _slot = slot;
            let fail = |waiters: Vec<tokio::sync::oneshot::Sender<_>>, message: String| {
                for waiter in waiters {
                    let _ = waiter.send(Err(message.clone()));
                }
            };
            let received = match submitted {
                Ok(receiver) => receiver.await,
                Err(fatal) => return fail(waiters, fatal.to_string()),
            };
            let response = match received {
                Ok(Ok(written)) => written.data,
                Ok(Err(err)) => return fail(waiters, err.to_string()),
                Err(_) => return fail(waiters, "metadata raft stopped".into()),
            };
            let mut waiters = waiters;
            if waiters.len() == 1 {
                if let Some(waiter) = waiters.pop() {
                    let _ = waiter.send(Ok(response));
                }
                return;
            }
            let mut each = response.each.into_iter();
            for waiter in waiters {
                let _ = waiter.send(
                    each.next()
                        .ok_or_else(|| "no response for a batched command".to_string()),
                );
            }
        });
    }
}

/// Linearizable reads. Each round confirms leadership once for every read
/// that was waiting when it started. A read that arrives during a round
/// waits for the next one, since that round may have begun before writes the
/// read must see.
async fn read_loop(
    raft: Raft<TypeConfig>,
    mut queue: tokio::sync::mpsc::Receiver<tokio::sync::oneshot::Sender<Result<(), String>>>,
) {
    while let Some(first) = queue.recv().await {
        let mut waiting = vec![first];
        while let Ok(next) = queue.try_recv() {
            waiting.push(next);
        }
        let result = raft
            .ensure_linearizable()
            .await
            .map(|_| ())
            .map_err(|err| err.to_string());
        for waiter in waiting {
            let _ = waiter.send(result.clone());
        }
    }
}

impl MetadataNode {
    /// Open the on-disk log and state machine and start Raft.
    ///
    /// `http_addr` is the address other brokers use for Raft RPC. The HTTP
    /// server itself is started by `camus-broker`.
    pub async fn open(node_id: NodeId, dir: &Path, http_addr: &str) -> anyhow::Result<Self> {
        let _ = http_addr;
        Self::start(node_id, dir, network::HttpFactory).await
    }

    /// Open a node whose Raft RPC stays in-process, routed by `group`.
    pub async fn open_in_process(
        node_id: NodeId,
        dir: &Path,
        group: &str,
        router: Arc<SharedRouter>,
    ) -> anyhow::Result<Self> {
        let factory = network::InProcFactory {
            group: group.to_string(),
            router,
        };
        Self::start(node_id, dir, factory).await
    }

    async fn start<N>(node_id: NodeId, dir: &Path, network: N) -> anyhow::Result<Self>
    where
        N: openraft::RaftNetworkFactory<TypeConfig>,
    {
        let (heartbeat_interval, election_timeout_min, election_timeout_max) =
            camus_raft::quic::raft_timeouts();
        let config = Config {
            heartbeat_interval,
            election_timeout_min,
            election_timeout_max,
            ..Default::default()
        };
        let config = Arc::new(config.validate()?);
        let log = camus_raft::SegmentLogStore::open(dir.join("log"))?;
        let machine = Arc::new(RedbMachine::open(&dir.join("state.redb"))?);
        let raft = Raft::new(node_id, config, network, log, machine.clone()).await?;
        let (writes, queued) = tokio::sync::mpsc::channel(QUEUED_WRITES);
        tokio::spawn(write_loop(raft.clone(), queued));
        let (reads, waiting) = tokio::sync::mpsc::channel(QUEUED_WRITES);
        tokio::spawn(read_loop(raft.clone(), waiting));
        Ok(Self {
            raft,
            machine,
            writes,
            reads,
        })
    }

    /// Register this in-process node so peers can reach it.
    pub fn register_in_process(&self, group: &str, node_id: NodeId, router: &SharedRouter) {
        router.insert(group, node_id, self.raft.clone());
    }

    /// Create the cluster. Call this once, on one voter, listing every voter.
    pub async fn initialize(&self, nodes: BTreeMap<NodeId, BasicNode>) -> anyhow::Result<()> {
        self.raft.initialize(nodes).await?;
        Ok(())
    }

    /// Commit a put. Fails when this node is not the leader.
    pub async fn write(
        &self,
        key: impl Into<String>,
        value: impl Into<String>,
    ) -> anyhow::Result<Response> {
        let response = self
            .submit(Command::Put {
                key: key.into(),
                value: value.into(),
            })
            .await?;
        Ok(response)
    }

    /// Commit a topic create. `error_code` is a Kafka code when the name is taken or the config is invalid.
    pub async fn create_topic(
        &self,
        name: impl Into<String>,
        partitions: i32,
        durability: impl Into<String>,
        configs: Vec<(String, Option<String>)>,
    ) -> anyhow::Result<Response> {
        let response = self
            .submit(Command::CreateTopic {
                name: name.into(),
                id: uuid::Uuid::new_v4().to_string(),
                partitions,
                durability: durability.into(),
                configs,
            })
            .await?;
        Ok(response)
    }

    /// Commit a topic delete.
    pub async fn delete_topic(&self, name: impl Into<String>) -> anyhow::Result<Response> {
        let response = self
            .submit(Command::DeleteTopic { name: name.into() })
            .await?;
        Ok(response)
    }

    /// Commit extent metadata. The object itself is already in the bucket.
    pub async fn publish(
        &self,
        parts: Vec<PublishPart>,
        producers: Vec<ProducerNote>,
    ) -> anyhow::Result<Response> {
        self.publish_with(parts, producers, Vec::new()).await
    }

    /// Publish extents and, in the same log entry, any transaction spans the
    /// object contains (ADR 0019). Empty `notes` is a plain publish.
    pub async fn publish_with(
        &self,
        parts: Vec<PublishPart>,
        producers: Vec<ProducerNote>,
        notes: Vec<Command>,
    ) -> anyhow::Result<Response> {
        let publish = Command::PublishWithProducers { parts, producers };
        let command = if notes.is_empty() {
            publish
        } else {
            let mut commands = Vec::with_capacity(1 + notes.len());
            commands.push(publish);
            commands.extend(notes);
            Command::Batch(commands)
        };
        let response = self.submit(command).await?;
        Ok(response)
    }

    /// Commit an admin or group command. `value` is command-specific.
    pub async fn apply(&self, command: Command) -> anyhow::Result<Response> {
        let response = self.submit(command).await?;
        Ok(response)
    }

    /// Allocate or bump a producer id. `value` is `"{producer_id},{epoch}"` on success.
    pub async fn init_producer(
        &self,
        transactional: bool,
        producer_id: i64,
        producer_epoch: i16,
    ) -> anyhow::Result<Response> {
        let response = self
            .submit(Command::InitProducer {
                transactional,
                producer_id,
                producer_epoch,
            })
            .await?;
        Ok(response)
    }

    /// Commit a group command and return its Kafka error code (0 = applied).
    pub async fn group_write(&self, command: Command) -> anyhow::Result<i16> {
        let response = self.submit(command).await?;
        Ok(response.error_code)
    }

    /// Wait until this node, as leader, has applied everything committed
    /// before the call, so a following [`MetadataNode::read_local`] is
    /// linearizable. Fails when this node is not the leader.
    pub async fn linearizable(&self) -> anyhow::Result<()> {
        let (done, wait) = tokio::sync::oneshot::channel();
        self.reads
            .send(done)
            .await
            .map_err(|_| anyhow::anyhow!("metadata read loop stopped"))?;
        wait.await
            .map_err(|_| anyhow::anyhow!("metadata read loop stopped"))?
            .map_err(anyhow::Error::msg)
    }

    /// Commit `command` through the group commit, and return its response.
    async fn submit(&self, command: Command) -> anyhow::Result<Response> {
        let (done, wait) = tokio::sync::oneshot::channel();
        self.writes
            .send((command, done))
            .await
            .map_err(|_| anyhow::anyhow!("metadata committer stopped"))?;
        wait.await
            .map_err(|_| anyhow::anyhow!("metadata committer stopped"))?
            .map_err(anyhow::Error::msg)
    }

    /// Applied keys starting with `prefix`, in key order. Not linearizable on
    /// its own; call [`MetadataNode::linearizable`] first when it must be.
    pub fn scan_local(&self, prefix: &str) -> anyhow::Result<Vec<(String, String)>> {
        Ok(self.machine.scan(prefix)?)
    }

    /// Up to `limit` locally applied keys in `[from, to)`, in key order. Not
    /// linearizable.
    pub fn scan_range_local(
        &self,
        from: &str,
        to: &str,
        limit: usize,
    ) -> anyhow::Result<Vec<(String, String)>> {
        Ok(self.machine.scan_range(from, to, limit)?)
    }

    /// Moves after every applied change that can alter the stored ACLs, once
    /// the change is readable. Compare it to know when a parsed copy is stale.
    pub fn acl_version(&self) -> u64 {
        self.machine.acl_version()
    }

    /// Read the latest applied value on this node. This is not a linearizable read.
    pub fn read_local(&self, key: &str) -> anyhow::Result<Option<String>> {
        Ok(self.machine.get(key)?)
    }

    /// Stop Raft tasks. The files stay on disk.
    /// Build a snapshot and return `(term, log index, body)` when this node
    /// leads the group and the snapshot covers a log entry.
    pub async fn snapshot_for_upload(&self) -> anyhow::Result<Option<(u64, u64, Vec<u8>)>> {
        let metrics = self.raft.metrics().borrow().clone();
        if metrics.current_leader != Some(metrics.id) {
            return Ok(None);
        }
        self.raft
            .trigger()
            .snapshot()
            .await
            .map_err(|err| anyhow::anyhow!(err))?;
        let Some((index, bytes)) = self.machine.snapshot_index_and_body().await else {
            return Ok(None);
        };
        Ok(Some((metrics.current_term, index, bytes)))
    }

    pub async fn shutdown(&self) -> anyhow::Result<()> {
        self.raft.shutdown().await?;
        Ok(())
    }
}
